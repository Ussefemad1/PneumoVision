/**
 * Generates packages/shared/src/generated/ehr-variables.ts from the training
 * code's discretizer config, so the web platform can never drift from the
 * feature order the LSTM was trained on.
 *
 * Source of truth: medpatch/ehr_utils/resources/discretizer_config.json
 * Run: npm run gen:ehr
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const configPath = resolve(root, 'medpatch/ehr_utils/resources/discretizer_config.json');
const outPath = resolve(root, 'packages/shared/src/generated/ehr-variables.ts');

const cfg = JSON.parse(readFileSync(configPath, 'utf8'));
const channels = cfg.id_to_channel;
const isCategorical = cfg.is_categorical_channel;
const possible = cfg.possible_values;
const normal = cfg.normal_values;

// Mirror Discretizer.transform(): one column per continuous channel, one column
// per possible value of a categorical channel, then one mask column per channel.
const columns = [];
for (const ch of channels) {
  if (isCategorical[ch]) {
    for (const v of possible[ch]) columns.push(ch + '->' + v);
  } else {
    columns.push(ch);
  }
}
const continuousIndices = columns.map((c, i) => (c.includes('->') ? -1 : i)).filter((i) => i >= 0);
const oneHotCount = columns.length - continuousIndices.length;
for (const ch of channels) columns.push('mask->' + ch);

/** Quote a string as a TS literal. JSON.stringify handles all escaping. */
const q = (s) => JSON.stringify(String(s));
const list = (arr, indent) => arr.map((c) => indent + q(c) + ',').join('\n');

const lines = [
  '// AUTO-GENERATED by infra/scripts/gen-ehr-constants.mjs — DO NOT EDIT BY HAND.',
  '// Source: medpatch/ehr_utils/resources/discretizer_config.json',
  '// Regenerate with: npm run gen:ehr',
  '',
  '/** The 17 clinical variables, in the exact order the discretizer emits them. */',
  'export const EHR_VARIABLES = [',
  list(channels, '  '),
  '] as const;',
  '',
  'export type EhrVariable = (typeof EHR_VARIABLES)[number];',
  '',
  '/** Variables the discretizer one-hot encodes. */',
  'export const EHR_CATEGORICAL_VARIABLES: readonly EhrVariable[] = [',
  list(
    channels.filter((c) => isCategorical[c]),
    '  ',
  ),
  '];',
  '',
  '/** Variables the discretizer keeps as a scalar and the Normalizer standardizes. */',
  'export const EHR_CONTINUOUS_VARIABLES: readonly EhrVariable[] = [',
  list(
    channels.filter((c) => !isCategorical[c]),
    '  ',
  ),
  '];',
  '',
  '/** Accepted raw values per categorical variable (verbatim MIMIC strings). */',
  'export const EHR_CATEGORICAL_VALUES: Readonly<Record<string, readonly string[]>> = {',
  channels
    .filter((c) => isCategorical[c])
    .map((c) => '  ' + q(c) + ': [' + possible[c].map(q).join(', ') + '],')
    .join('\n'),
  '};',
  '',
  '/** Discretizer fallback used when a variable was never charted. */',
  'export const EHR_NORMAL_VALUES: Readonly<Record<EhrVariable, string>> = {',
  channels.map((c) => '  ' + q(c) + ': ' + q(normal[c]) + ',').join('\n'),
  '};',
  '',
  '/**',
  ' * The ' + columns.length + ' columns the discretizer produces per hourly bin:',
  ' * ' +
    continuousIndices.length +
    ' continuous + ' +
    oneHotCount +
    ' one-hot + ' +
    channels.length +
    ' mask.',
  ' * The LSTM input is [batch, 48, ' + columns.length + '] — NOT 17 features wide.',
  ' */',
  'export const EHR_DISCRETIZED_COLUMNS = [',
  list(columns, '  '),
  '] as const;',
  '',
  'export const EHR_DISCRETIZED_WIDTH = ' + columns.length + ' as const;',
  '',
  '/** Column indices the Normalizer standardizes (the continuous ones only). */',
  'export const EHR_CONTINUOUS_COLUMN_INDICES = [' + continuousIndices.join(', ') + '] as const;',
  '',
  '/** MedPatch uses a 48-hour, 1-hour-binned window (paper §4.2). */',
  'export const EHR_WINDOW_HOURS = 48 as const;',
  'export const EHR_TIMESTEP_HOURS = 1 as const;',
  '',
];

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, lines.join('\n'), 'utf8');
console.log(
  'wrote ' +
    outPath +
    '\n  ' +
    channels.length +
    ' variables -> ' +
    columns.length +
    ' discretized columns (' +
    continuousIndices.length +
    ' continuous, ' +
    oneHotCount +
    ' one-hot, ' +
    channels.length +
    ' mask)',
);
